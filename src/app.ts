import cors from 'cors';
import express from 'express';
import helmet from 'helmet';
import { config } from './config.js';
import { errorHandler } from './lib/errors.js';
import { dashboardRouter } from './routes/dashboard.js';
import { categoriesRouter } from './routes/categories.js';
import { entriesRouter } from './routes/entries.js';
import { recurringRouter } from './routes/recurring.js';
import { budgetsRouter } from './routes/budgets.js';
import { shoppingRouter } from './routes/shopping.js';
import { authRouter } from './routes/auth.js';
import { spacesRouter } from './routes/spaces.js';
import { sharedExpensesRouter } from './routes/shared-expenses.js';
import { settlementsRouter } from './routes/settlements.js';
import { requireActiveSpace, requireAuthentication, requireCsrfForMutations, requireSpaceContext, requireTenantDataReady } from './lib/request-context.js';

export const app = express();
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin: config.FRONTEND_ORIGIN, credentials: true }));
app.use(express.json({ limit: '100kb' }));
app.get('/api/health', (_request, response) => response.json({ status: 'ok' }));
app.use('/api/auth', authRouter);
app.use('/api/spaces', requireAuthentication, requireTenantDataReady, requireCsrfForMutations, spacesRouter);
app.use('/api/settlements', requireAuthentication, requireTenantDataReady, requireSpaceContext, requireCsrfForMutations, settlementsRouter);
app.use('/api', requireAuthentication, requireTenantDataReady, requireSpaceContext, requireCsrfForMutations, requireActiveSpace);
app.use('/api/shared-expenses', sharedExpensesRouter);
app.use('/api/dashboard', dashboardRouter);
app.use('/api/categories', categoriesRouter);
app.use('/api/entries', entriesRouter);
app.use('/api/recurring', recurringRouter);
app.use('/api/budgets', budgetsRouter);
app.use('/api/shopping', shoppingRouter);
app.use((_request, response) => response.status(404).json({ error: 'Ruta no encontrada.' }));
app.use(errorHandler);
